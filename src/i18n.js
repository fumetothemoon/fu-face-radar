const LANG_KEY = "ffr-lang";
export function initialLang() {
  try { const s = localStorage.getItem(LANG_KEY); if (s === "en" || s === "zh") return s; } catch { /* private mode */ }
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language || "en"];
  return langs.some((l) => /^zh\b/i.test(l)) ? "zh" : "en";
}
export function rememberLang(lang) { try { localStorage.setItem(LANG_KEY, lang); } catch { /* private mode */ } }

export const LangContext = createContext("en");
export const useLang = () => useContext(LangContext);
export const useT = () => STRINGS[useLang()];
